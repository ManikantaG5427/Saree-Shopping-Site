export const getProductById = (id) => {
  return products.find(p => p.id === id);
};

export const getProductsByCategory = (category) => {
  return products.filter(p => p.category.toLowerCase() === category.toLowerCase() && p.isActive);
};

export const searchProducts = (query) => {
  const lowercaseQuery = (query || '').toLowerCase();
  return products.filter(p => 
    p.isActive && (
      p.name.toLowerCase().includes(lowercaseQuery) ||
      p.description.toLowerCase().includes(lowercaseQuery) ||
      p.category.toLowerCase().includes(lowercaseQuery) ||
      (p.fabric && p.fabric.toLowerCase().includes(lowercaseQuery)) ||
      (p.occasion && p.occasion.toLowerCase().includes(lowercaseQuery)) ||
      p.tags.some(tag => tag.toLowerCase().includes(lowercaseQuery))
    )
  );
};

export const getFeaturedProducts = (limit = 8) => {
  return products.filter(p => p.isActive && (p.isFeatured || p.tags?.includes('top-picks'))).slice(0, limit);
};

export const getNewArrivals = (limit = 8) => {
  return [...products].filter(p => p.isActive).sort((a, b) => new Date(b.createdAt).getTime() - new Date(a.createdAt).getTime()).slice(0, limit);
};

export const getBestSellers = (limit = 8) => {
  return [...products].filter(p => p.isActive).sort((a, b) => b.reviewCount - a.reviewCount).slice(0, limit);
};
